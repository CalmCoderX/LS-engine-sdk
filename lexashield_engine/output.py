def _generate_hash(text: str, algorithm: str = "sha256") -> str:
    if algorithm == "sha256":
        return "sha256:" + hashlib.sha256(text.encode("utf-8")).hexdigest()
    elif algorithm == "md5":
        return "md5:" + hashlib.md5(text.encode("utf-8")).hexdigest()
    raise ValueError(f"Unsupported hash algorithm: {algorithm}")


def _get_timestamp_utc() -> str:
    return datetime.datetime.now(datetime.timezone.utc).isoformat().replace("+00:00", "Z")


def _get_legal_disclaimer(language: str = "en-US") -> str:
    if normalize_language(language).lower().startswith("pt"):
        return LEGAL_DISCLAIMER_PT
    return LEGAL_DISCLAIMER_EN


def _get_important_notice(language: str = "en-US") -> str:
    if normalize_language(language).lower().startswith("pt"):
        return IMPORTANT_NOTICE_PT
    return IMPORTANT_NOTICE_EN


def _get_output_language(output_dict: Dict[str, Any]) -> str:
    if not isinstance(output_dict, dict):
        return "en-US"
    lib = output_dict.get("Library")
    if isinstance(lib, dict) and lib.get("Language"):
        return normalize_language(str(lib.get("Language")))
    rm = output_dict.get("Report Metadata")
    if isinstance(rm, dict) and rm.get("Language"):
        return normalize_language(str(rm.get("Language")))
    engine = output_dict.get("Engine")
    if isinstance(engine, dict) and engine.get("Language"):
        return normalize_language(str(engine.get("Language")))
    return "en-US"


def _clean_name(name: str) -> str:
    if not name:
        return "Untitled"
    name_without_ext = os.path.splitext(name)[0]
    return name_without_ext.replace("_", " ").replace("-", " ").title()


def _get_confidence_level(score: float) -> str:
    if score >= 0.90:
        return "very_high"
    elif score >= 0.75:
        return "high"
    elif score >= 0.60:
        return "medium"
    elif score >= 0.40:
        return "low"
    return "very_low"


def _load_private_key(key_path: str = None):
    global _PRIVATE_KEY
    if _PRIVATE_KEY is not None:
        return _PRIVATE_KEY
    if not CRYPTO_AVAILABLE:
        raise ImportError("cryptography library required. Install: pip install cryptography")
    key_path = key_path or PRIVATE_KEY_PATH
    with open(key_path, "rb") as f:
        _PRIVATE_KEY = serialization.load_pem_private_key(
            f.read(), password=None, backend=default_backend()
        )
    return _PRIVATE_KEY


def refresh_output_signature(output_dict: Dict[str, Any]) -> None:
    """
    Recompute the RSA-PSS signature after the output dict was mutated (e.g. platform library metadata).
    Matches the signing step in format_complete_output(): signs the dict without a Signature key, then re-attaches Signature.
    """
    if not SIGNATURE_ENABLED:
        return
    output_dict.pop("Signature", None)
    sig = _sign_output(output_dict)
    if not sig or str(sig).startswith("SIGNATURE_"):
        return
    display_language = _get_output_language(output_dict)
    output_dict["Signature"] = {
        "Value": sig,
        "Algorithm": "RSA-PSS-SHA256",
        "Key Size": 2048,
        "Note": _get_important_notice(display_language),
    }


def _sign_output(output_dict: Dict[str, Any]) -> str:
    if not CRYPTO_AVAILABLE:
        return "SIGNATURE_UNAVAILABLE_INSTALL_CRYPTOGRAPHY"
    if not SIGNATURE_ENABLED:
        return None
    try:
        private_key = _load_private_key()
        canonical_json = json.dumps(output_dict, sort_keys=True, separators=(",", ":"))
        signature = private_key.sign(
            canonical_json.encode("utf-8"),
            padding.PSS(
                mgf=padding.MGF1(hashes.SHA256()),
                salt_length=padding.PSS.MAX_LENGTH
            ),
            hashes.SHA256()
        )
        return base64.b64encode(signature).decode("utf-8")
    except Exception as e:
        import warnings
        warnings.warn(f"Failed to sign output: {e}")
        return f"SIGNATURE_ERROR_{type(e).__name__}"


def extract_compliance_signature_for_task_metadata(results: Any) -> Optional[str]:
    """
    Value for ``processing_tasks.result_metadata['Compliance Signature']`` on the backend
    (``Report Metadata`` / ``Session.Hash``).
    """
    first: Any = None
    if isinstance(results, list) and len(results) > 0:
        first = results[0]
    elif isinstance(results, dict):
        first = results
    if not isinstance(first, dict):
        return None
    sess = first.get("Session")
    if isinstance(sess, dict):
        h = sess.get("Hash")
        if h is not None and str(h).strip() and str(h).strip().upper() != "N/A":
            return str(h).strip()
    return None


